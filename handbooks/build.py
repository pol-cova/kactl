#!/usr/bin/env python3
"""Build native KACTL landscape, three-column companions from tested helpers."""
from pathlib import Path
import argparse
import os
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
MATH = ['IntegerDivision','ExactDecimals','ModularArithmetic','EuclidCRT',
        'FactorSieve','DecimalPeriod','Combinations','Inversions',
        'FuzzyFactorization','IntegerGeometry']
CORE = ['BFS','Components','GridBFS','WeightedPaths','TopoSort','DSUKruskal',
        'TreeLCA','CompressionPrefix','IntervalUnion','DifferenceArray','SlidingWindow',
        'BinarySearch','Fenwick','SegmentTree','Knapsack','LIS']
MATH_DEPS = {'ExactDecimals':['IntegerDivision'],
             'EuclidCRT':['IntegerDivision','ModularArithmetic'],
             'DecimalPeriod':['ExactDecimals','ModularArithmetic','FactorSieve'],
             'Combinations':['ModularArithmetic'],
             'Inversions':['IntegerDivision'],
             'FuzzyFactorization':['FactorSieve']}
CASES = ['Fundraising','HazardEscape','ToggleSubsets','CapacitySearch','ExactSum']
CORE_DEPS = {'GridBFS':['BFS']}

def annotated(body, description, dependencies=()):
    return ('/**\n * Author: Mexico finals team / Codex\n'
        ' * Date: 2026-10-18\n * License: CC0\n'
        ' * Source: handbooks/include; generated by handbooks/build.py\n'
        ' * Description: '+description+'\n'
        ' * Status: Local oracle and sanitizer tests; see handbooks/VALIDATION.md.\n'
        ' */\n#pragma once\n'+''.join('#include "'+d+'.h"\n' for d in dependencies)
        +'\n'+body.rstrip()+'\n')

def generate(header, names, folder, namespace, dependencies):
    target=ROOT/'content'/folder
    target.mkdir(parents=True,exist_ok=True)
    source=(ROOT/'handbooks/include'/header).read_text()
    chunks=re.split(r'^// BOOK: (.+)$',source,flags=re.M)
    assert len(chunks)==1+2*len(names)
    prelude=chunks[0].replace('#pragma once\n','')
    (target/'Prelude.h').write_text(annotated(prelude+'\n} // namespace '+namespace,
        'Shared includes, aliases and bounds. Include before the modules.'))
    for i,name in enumerate(names):
        title,body=chunks[2*i+1:2*i+3]
        body=re.sub(r'\n}\s*// namespace '+namespace+r'\s*$','',body.rstrip())
        body='namespace '+namespace+' {\n'+body.strip()+'\n} // namespace '+namespace
        deps=['Prelude']+dependencies.get(name,[])
        (target/(name+'.h')).write_text(annotated(body,
            title+'.',deps))

def generate_digit():
    source=(ROOT/'handbooks/include/digit_dp.hpp').read_text()
    source=source.replace('#pragma once\n','')
    source=re.sub(r'^// BOOK: .*\n','',source,flags=re.M)
    (ROOT/'content/finals-implementations/DigitDP.h').write_text(annotated(source,
        'Smallest divisible decimal-pattern completion. O(L*m*10) time, O(L*m) memory.'))

def environment():
    env=os.environ.copy()
    env['TEXINPUTS']='.:content/tex/:'+env.get('TEXINPUTS','')
    # Hashing uses GNU cpp flags. macOS /usr/bin/cpp is Clang; use an installed
    # GNU cpp when available without modifying KACTL's hashing implementation.
    for version in range(16,10,-1):
        cpp=shutil.which('cpp-'+str(version))
        if cpp:
            shim=ROOT/'build/handbooks-tools';shim.mkdir(parents=True,exist_ok=True)
            link=shim/'cpp'
            if not link.exists(): link.symlink_to(cpp)
            env['PATH']=str(shim)+os.pathsep+env['PATH'];break
    return env

def build():
    (ROOT/'build').mkdir(exist_ok=True)
    output=ROOT/'handbooks/pdf';output.mkdir(exist_ok=True)
    for job,name in [('finals-math','math-handbook'),
                     ('finals-implementations','implementation-handbook'),
                     ('finals-patterns','patterns-workbook')]:
        log=ROOT/'build'/(job+'-build.txt')
        args=['pdflatex','-shell-escape','-interaction=nonstopmode',
              '-halt-on-error','-output-directory=build',f'content/{job}.tex']
        for _ in range(3):
            with log.open('w') as stream:
                done=subprocess.run(args,cwd=ROOT,env=environment(),
                    stdout=stream,stderr=subprocess.STDOUT)
            if done.returncode:
                print(log.read_text()[-9000:]);raise SystemExit(done.returncode)
        shutil.copy2(ROOT/'build'/(job+'.pdf'),output/(name+'.pdf'))
        print(output/(name+'.pdf'))

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--generate-only',action='store_true')
    opts=parser.parse_args()
    generate('math.hpp',MATH,'finals-math','finals_math',MATH_DEPS)
    generate('core.hpp',CORE,'finals-implementations','finals_core',CORE_DEPS)
    generate_digit()
    generate('case_studies.hpp',CASES,'finals-patterns','finals_cases',{})
    generate('practical.hpp',['LinkedSort','AtomicInventory','OfflineThreshold'],
             'finals-practical','finals_practical',{'OfflineThreshold':['LinkedSort']})
    generate('math_extra.hpp',['Divisors','PrimeExponents','GCDPairs','GCDOrbits'],
             'finals-math-extra','finals_math_extra',{})
    generate('dp_extra.hpp',['SubsetOrder','TreeMatching','SubtreeRanges','Unranking'],
             'finals-dp-extra','finals_dp_extra',{})
    if not opts.generate_only:build()
